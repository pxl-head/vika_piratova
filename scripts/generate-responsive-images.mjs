import { execFile } from "node:child_process";
import { mkdir, readdir, stat, writeFile } from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { promisify } from "node:util";

const execFileAsync = promisify(execFile);
const projectRoot = fileURLToPath(new URL("../", import.meta.url));
const imagesRoot = path.join(projectRoot, "public/images");
const responsiveRoot = path.join(imagesRoot, "responsive");
const manifestPath = path.join(projectRoot, "src/data/imageMeta.generated.ts");
const targetWidths = [640, 1280];
const supportedExtensions = new Set([".jpg", ".jpeg", ".png", ".webp"]);

async function listImages(directory) {
  const images = [];

  for (const entry of await readdir(directory, { withFileTypes: true })) {
    if (entry.isDirectory() && entry.name === "responsive") continue;

    const absolutePath = path.join(directory, entry.name);
    if (entry.isDirectory()) {
      images.push(...(await listImages(absolutePath)));
    } else if (supportedExtensions.has(path.extname(entry.name).toLowerCase())) {
      images.push(absolutePath);
    }
  }

  return images;
}

async function mapWithConcurrency(items, worker) {
  const results = new Array(items.length);
  let cursor = 0;
  const concurrency = Math.min(6, Math.max(2, os.cpus().length - 1));

  await Promise.all(
    Array.from({ length: concurrency }, async () => {
      while (cursor < items.length) {
        const index = cursor;
        cursor += 1;
        results[index] = await worker(items[index]);
      }
    }),
  );

  return results;
}

async function getDimensions(file) {
  const { stdout } = await execFileAsync("magick", [
    file,
    "-auto-orient",
    "-format",
    "%w %h",
    "info:",
  ]);
  const [width, height] = stdout.trim().split(/\s+/).map(Number);
  return { width, height };
}

async function generateVariant(source, destination, width) {
  await mkdir(path.dirname(destination), { recursive: true });

  const sourceStats = await stat(source);
  let destinationIsCurrent = false;
  try {
    destinationIsCurrent = (await stat(destination)).mtimeMs >= sourceStats.mtimeMs;
  } catch {
    // The variant does not exist yet.
  }

  if (destinationIsCurrent) return;

  await execFileAsync("magick", [
    source,
    "-auto-orient",
    "-resize",
    `${width}x>`,
    "-quality",
    "86",
    "-define",
    "webp:method=6",
    destination,
  ]);
}

const files = (await listImages(imagesRoot)).sort((a, b) => a.localeCompare(b));

const records = await mapWithConcurrency(files, async (file) => {
  const relativePath = path.relative(imagesRoot, file);
  const webPath = `/images/${relativePath.split(path.sep).join("/")}`;
  const extension = path.extname(relativePath);
  const stem = relativePath.slice(0, -extension.length);
  const { width, height } = await getDimensions(file);
  const sources = [];

  for (const targetWidth of targetWidths) {
    if (width <= targetWidth) continue;

    const destinationRelative = `${stem}-${targetWidth}.webp`;
    const destination = path.join(responsiveRoot, destinationRelative);
    await generateVariant(file, destination, targetWidth);
    sources.push({
      src: `/images/responsive/${destinationRelative.split(path.sep).join("/")}`,
      width: targetWidth,
    });
  }

  sources.push({ src: webPath, width });
  return [webPath, { width, height, sources }];
});

const manifest = `// Generated by npm run images:generate. Do not edit by hand.\nexport const IMAGE_META = ${JSON.stringify(
  Object.fromEntries(records),
  null,
  2,
)} as const;\n`;

await writeFile(manifestPath, manifest, "utf8");
console.log(`Generated responsive metadata for ${records.length} images.`);
